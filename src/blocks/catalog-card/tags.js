/**
 * Теги карточки каталога хранятся одной строкой через запятую — так их
 * правит редактор в инспекторе, без отдельного повторяемого поля. Разбор
 * общий для `edit.js` и `save.js`, чтобы разметка совпадала (иначе
 * Gutenberg сочтёт блок «сломанным» при валидации).
 */
export function splitTags( value ) {
	return ( value || '' )
		.split( ',' )
		.map( ( tag ) => tag.trim() )
		.filter( Boolean );
}
